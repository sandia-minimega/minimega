package iomeshage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
	"time"

	log "github.com/sandia-minimega/minimega/v2/pkg/minilog"

	"github.com/fsnotify/fsnotify"
	"github.com/twmb/murmur3"
)

// ignoredDirectories is a list of strings that cause a path to be ignored by
// the hasher. A path is ignored when any of its components starts with one of
// the strings. This includes the file name and the components of the base
// directory.
//
// transfer_ - don't hash file parts as they're being transferred. Instead, just
// wait for the CREATE event for the final, combined file.
var ignoredDirectories = []string{"transfer_"}

// hashDelay is how long a file must go without changing before it is hashed,
// so a file is hashed once after a copy instead of once per write to it.
var hashDelay = 2 * time.Second

// hashWorkers is the maximum number of files hashed at the same time.
var hashWorkers = max(1, runtime.NumCPU()/2)

// hashJob tracks the pending or running hash of a single file.
type hashJob struct {
	gen    uint64             // incremented each time the file changes
	timer  *time.Timer        // fires once the file has been quiet for hashDelay
	cancel context.CancelFunc // aborts the running hash, if any
}

// hasher hashes files in the background once they stop changing.
type hasher struct {
	iom     *IOMeshage
	watcher *fsnotify.Watcher
	sem     chan struct{} // limits concurrent hashing
	hash    func(context.Context, string) (string, error)

	// mu guards jobs, and hash updates so a stale result can't replace a newer one
	mu   sync.Mutex
	jobs map[string]*hashJob

	// dirs is the set of watched directories, used only by the start goroutine
	dirs map[string]bool
}

func newHasher(iom *IOMeshage, watcher *fsnotify.Watcher) *hasher {
	return &hasher{
		iom:     iom,
		watcher: watcher,
		sem:     make(chan struct{}, hashWorkers),
		hash:    hashFile,
		jobs:    make(map[string]*hashJob),
		dirs:    make(map[string]bool),
	}
}

// startHasher generates a Murmur3 hash for all existing files and also watches
// for new or updated files and generates a hash for them as well.
func (iom *IOMeshage) startHasher() {
	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		log.Fatal("creating file watcher: %v", err)
	}

	defer watcher.Close()

	h := newHasher(iom, watcher)

	// This goroutine hashes the existing files, and then continually processes
	// events generated by the fsnotify watcher and hashes files in the background
	// as needed to help speed things up when the hash actually needs to be used.
	go h.start()

	// Prevent this function from ever returning so the fsnotify event processing
	// goroutine will stay in scope.
	<-make(chan struct{})
}

// start schedules a hash for the files already in the base directory, and then
// processes file system events until the watcher is closed.
//
// addDir watches each directory before it scans it, so a file created during
// the scan is not missed. Its event stays in the queue until the scan is
// complete. A directory that cannot be watched is still scanned. The scan and
// the event processing run on the same goroutine because both use dirs.
func (h *hasher) start() {
	h.addDir(h.iom.base)
	h.watch()
}

// watch processes file system events until the watcher is closed.
func (h *hasher) watch() {
	for {
		select {
		case event, ok := <-h.watcher.Events:
			if !ok {
				return
			}

			h.handleEvent(event)
		case err, ok := <-h.watcher.Errors:
			if !ok {
				return
			}

			log.Error("watching for file events: %v", err)
		}
	}
}

func (h *hasher) handleEvent(event fsnotify.Event) {
	// A removed or renamed path no longer exists, so checking it for a symlink
	// tells us nothing. The new name of a renamed file gets its own CREATE event.
	if event.Has(fsnotify.Remove) || event.Has(fsnotify.Rename) {
		if !ignoreDirectory(event.Name) {
			log.Debug("deleting hash for file %s", event.Name)
			h.forget(event.Name)
		}

		return
	}

	if ignoreDirectory(event.Name) {
		return
	}

	// A symlink or an empty file moved over a hashed file gets only a CREATE
	// event, so drop the old hash here.
	if isLink(event.Name) {
		if event.Has(fsnotify.Create) {
			h.forget(event.Name)
		}

		return
	}

	log.Debug("new file system event: %s", event)

	if event.Has(fsnotify.Create) {
		stat, err := os.Stat(event.Name)
		if err != nil {
			log.Error("getting stats for newly created file %s: %v", event.Name, err)
			return
		}

		if stat.IsDir() {
			log.Debug("adding new directory %s to file system watcher", event.Name)
			h.addDir(event.Name)
		} else if stat.Size() > 0 {
			h.schedule(event.Name)
		} else {
			h.forget(event.Name)
		}
	}

	if event.Has(fsnotify.Write) {
		h.schedule(event.Name)
	}
}

// addDir watches dir and everything below it, and schedules a hash for the
// files already there. Directories created with content (cp -r, mkdir -p)
// would otherwise have that content missed. When dir cannot be watched (for
// example, at the inotify watch limit), its files are still hashed one time.
func (h *hasher) addDir(dir string) {
	if err := h.watcher.Add(dir); err != nil {
		log.Error("watching directory %s: %v", dir, err)
	} else {
		h.dirs[dir] = true
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		log.Error("listing directory %s: %v", dir, err)
		return
	}

	for _, entry := range entries {
		path := filepath.Join(dir, entry.Name())

		if ignoreDirectory(path) || entry.Type()&os.ModeSymlink != 0 {
			continue
		}

		if entry.IsDir() {
			h.addDir(path)
			continue
		}

		if info, err := entry.Info(); err == nil && info.Mode().IsRegular() && info.Size() > 0 {
			h.schedule(path)
		}
	}
}

// schedule hashes path once it has not changed for hashDelay. Until then the
// file has no hash, since the old one no longer describes its contents. Only
// regular files are hashed: opening a FIFO or a device can block forever.
func (h *hasher) schedule(path string) {
	info, err := os.Lstat(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		// the contents changed, but cannot be read to hash them again
		h.mu.Lock()
		defer h.mu.Unlock()

		h.iom.updateHash(path, "")

		return
	}

	if err != nil || !info.Mode().IsRegular() {
		return
	}

	h.mu.Lock()
	defer h.mu.Unlock()

	job := h.jobs[path]
	if job == nil {
		job = new(hashJob)
		h.jobs[path] = job

		h.iom.updateHash(path, "")
	}

	job.stop()
	job.gen++

	gen := job.gen
	job.timer = time.AfterFunc(hashDelay, func() { h.run(path, job, gen) })
}

// run hashes path for job, unless the file changed again since gen was
// scheduled or the job was replaced.
func (h *hasher) run(path string, job *hashJob, gen uint64) {
	h.sem <- struct{}{}
	defer func() { <-h.sem }()

	h.mu.Lock()

	if h.jobs[path] != job || job.gen != gen {
		h.mu.Unlock()
		return
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	job.cancel = cancel
	h.mu.Unlock()

	log.Debug("getting hash for file %s", path)
	hash, err := h.hash(ctx, path)

	h.mu.Lock()
	defer h.mu.Unlock()

	// the file changed or was removed while it was being hashed
	if h.jobs[path] != job || job.gen != gen {
		return
	}

	delete(h.jobs, path)

	if err != nil {
		log.Error("getting hash for file %s: %v", path, err)
		return
	}

	h.iom.updateHash(path, hash)
}

// forget drops the hash, and any pending hashing, of path and of everything
// below it if it was a directory.
func (h *hasher) forget(path string) {
	// only a watched directory can have anything below it
	if !h.dirs[path] {
		h.mu.Lock()
		defer h.mu.Unlock()

		if job := h.jobs[path]; job != nil {
			job.stop()
			delete(h.jobs, path)
		}

		h.iom.updateHash(path, "")

		return
	}

	below := path + string(filepath.Separator)

	// A renamed directory's watches would keep reporting events under its old
	// name. The CREATE event for the new name watches it again.
	for dir := range h.dirs {
		if dir == path || strings.HasPrefix(dir, below) {
			h.watcher.Remove(dir)
			delete(h.dirs, dir)
		}
	}

	h.mu.Lock()
	defer h.mu.Unlock()

	for p, job := range h.jobs {
		if p == path || strings.HasPrefix(p, below) {
			job.stop()
			delete(h.jobs, p)
		}
	}

	h.iom.deleteHashes(path)
}

// stop cancels the job's timer and its running hash.
func (j *hashJob) stop() {
	if j.timer != nil {
		j.timer.Stop()
	}

	if j.cancel != nil {
		j.cancel()
		j.cancel = nil
	}
}

// ctxReader stops reading once its context is cancelled.
type ctxReader struct {
	ctx context.Context
	r   io.Reader
}

func (c ctxReader) Read(p []byte) (int, error) {
	if err := c.ctx.Err(); err != nil {
		return 0, err
	}

	return c.r.Read(p)
}

// hashFile takes a filepath, resolves symlinks, and returns a murmur3 hash.
// Cancelling ctx aborts the hash.
func hashFile(ctx context.Context, path string) (string, error) {
	// Resolve the symbolic link to the actual file path.
	// This ensures we hash the content of the target file, not the link itself.
	realPath, err := filepath.EvalSymlinks(path)
	if err != nil {
		return "", fmt.Errorf("error resolving symlink for %s: %w", path, err)
	}

	file, err := os.Open(realPath)
	if err != nil {
		return "", fmt.Errorf("opening file %s for hashing: %w", realPath, err)
	}

	defer file.Close()
	start := time.Now()

	hasher := murmur3.New64()
	if _, err := io.CopyBuffer(hasher, ctxReader{ctx, file}, make([]byte, 1<<20)); err != nil {
		return "", fmt.Errorf("hashing file: %w", err)
	}

	hash := fmt.Sprintf("%x", hasher.Sum(nil))

	if realPath != path {
		log.Debug("hashing %s (via symlink %s) took %s", realPath, path, time.Since(start))
	} else {
		log.Debug("hashing %s took %s", path, time.Since(start))
	}

	return hash, nil
}

// ignoreDirectory checks to see if any component of the given path, including
// the file name, starts with one of the ignoredDirectories.
func ignoreDirectory(path string) bool {
	for _, part := range strings.Split(filepath.ToSlash(path), "/") {
		for _, ignore := range ignoredDirectories {
			// match the start of a name, not the string anywhere in a name
			if strings.HasPrefix(part, ignore) {
				return true
			}
		}
	}

	return false
}

// isLink checks to see if the given path is a symbolic link.
func isLink(path string) bool {
	fileInfo, err := os.Lstat(path)
	if err != nil {
		return false
	}

	return fileInfo.Mode()&os.ModeSymlink != 0
}
